"""业务模块台账注册表：所有模块的中文名、字段口径都在这里集中登记。

流水线（种子迁移、跨日补录、对账、汇总重算）只认这一份台账，
避免去逐个 import 18 个 service 后再猜字段。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ModuleSpec:
    """单个业务模块的台账口径。"""

    name: str  # 英文模块名，也是 store 表名、路由前缀
    label: str  # 中文名，用于概览与前端导航
    code_prefix: str  # 业务编号前缀
    required_fields: tuple[str, ...]  # 必填字段（登记与补录都会带上）
    all_fields: tuple[str, ...]  # 列表/台账展示字段顺序
    statuses: tuple[str, ...]  # 状态序列
    actions: tuple[str, ...]  # 可执行动作
    date_field: str  # 业务日期字段：跨日补录按业务时区改写它
    # 动作 -> 目标状态；不按“动作序号+1”顺序映射的模块在此显式声明。
    # 缺省时按注册表顺序 actions[i] -> statuses[i+1] 推导。
    action_targets: dict[str, str] | None = None

    def target_of(self, action: str) -> str | None:
        """返回动作落到的目标状态，未知动作返回 None。"""
        if self.action_targets is not None:
            return self.action_targets.get(action)
        if action not in self.actions:
            return None
        index = self.actions.index(action)
        target_index = min(index + 1, len(self.statuses) - 1)
        return self.statuses[target_index]


